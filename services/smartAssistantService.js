// 🧠 PREPARE CONVERSATION MEMORY
// ======================================================

function prepareConversationHistory(
    conversation = []
){

    if(!Array.isArray(conversation)){
        return [];
    }

    return conversation
        .filter(item => {

            return (
                item &&
                (
                    item.role === "user" ||
                    item.role === "assistant"
                ) &&
                typeof item.content === "string" &&
                item.content.trim()
            );

        })
        .slice(-15)
        .map(item => ({

            role:
                item.role,

            content:
                item.content

        }));

}

